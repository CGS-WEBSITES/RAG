PROJECT_CHARACTER_MAP = {
    "Drunagor": "Drunagor",
    "Dante": "Dante",
    "Battleforge": "Battleforge",
    "Forfun": "Forfun",
}


def get_character_prompt(project: str | None, region: str | None = None) -> str | None:
    if not project:
        return None
    key = PROJECT_CHARACTER_MAP.get(project)
    if not key:
        return None
    base_prompt = CHARACTER_PROMPTS[key]["prompt"]
    if project and region:
        context_block = (
            f"\n\nACTIVE CONTEXT (mandatory — always follow this):\n"
            f"- This conversation is specifically about the '{project}' project in the '{region}' region.\n"
            f"- ALWAYS mention '{project}' and '{region}' explicitly when discussing shipping, logistics or order status.\n"
            f"- Example: instead of 'your order', say 'your {project} order in {region}' or translate naturally into your world's language."
        )
        # Inject context block right before STRICT RULES so it has high priority
        if "STRICT RULES:" in base_prompt:
            base_prompt = base_prompt.replace(
                "STRICT RULES:", context_block + "\n\nSTRICT RULES:"
            )
        else:
            base_prompt += context_block
    return base_prompt


def get_character_name(project: str | None) -> str | None:
    if not project:
        return None
    key = PROJECT_CHARACTER_MAP.get(project)
    if not key:
        return None
    return CHARACTER_PROMPTS[key]["name"]
