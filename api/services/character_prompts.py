def get_character_prompt(project: str | None) -> str | None:
    if not project:
        return None
    key = PROJECT_CHARACTER_MAP.get(project)
    if not key:
        return None
    return CHARACTER_PROMPTS[key]["prompt"]


def get_character_name(project: str | None) -> str | None:
    if not project:
        return None
    key = PROJECT_CHARACTER_MAP.get(project)
    if not key:
        return None
    return CHARACTER_PROMPTS[key]["name"]
